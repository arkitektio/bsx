// Writes src/tailwind/defaultTheme.ts: the default theme the runtime Tailwind reads
// (`configureBlokPlatform({tailwindTheme})` replaces it), as a string module, so the
// package imports no `?raw` CSS outside `./tailwind` (Metro has no `?raw`).
import {readFileSync, writeFileSync} from 'node:fs';

const css = readFileSync(new URL('../src/tailwind/theme.css', import.meta.url), 'utf8');
writeFileSync(
  new URL('../src/tailwind/defaultTheme.ts', import.meta.url),
  `// Generated by scripts/embed-theme.mjs from theme.css; do not edit.\nconst theme: string = ${JSON.stringify(css)};\nexport default theme;\n`,
);
