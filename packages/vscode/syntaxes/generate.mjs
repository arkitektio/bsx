// Writes the two injection grammars that colour BSX inside Python strings, from bsx.tmLanguage.json.
//
// A blok is a Python string whose text starts with a root that names its context (`<Html>`,
// `<Scene>`, ..., vocabulary.json `blok_roots`), so an injection begins there and ends before the
// string's closing quote. Every rule of the copy also ends at that quote: an author mid-way through
// `<Card ` must not have the tag swallow the `"""` and colour the rest of the file as BSX.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const bsx = JSON.parse(readFileSync(join(here, 'bsx.tmLanguage.json'), 'utf8'));
const vocabulary = JSON.parse(readFileSync(join(here, '../../bsx/src/spec/vocabulary.json'), 'utf8'));
const roots = Object.keys(vocabulary.blok_roots.roots).join('|');

const variants = [
  {
    file: 'bsx-in-python-multi.tmLanguage.json',
    scopeName: 'bsx.injection.python.multi',
    strings: ['string.quoted.multi.python', 'string.quoted.raw.multi.python'],
    content: 'meta.embedded.block.bsx',
    terminator: `(?="""|''')`,
  },
  {
    // A single-quoted string ends on its line; its closing quote is the one a call's `,`/`)` or
    // the line's end follows (an attribute's quote is followed by a space, `/` or `>`).
    file: 'bsx-in-python-single.tmLanguage.json',
    scopeName: 'bsx.injection.python.single',
    strings: ['string.quoted.single.python', 'string.quoted.raw.single.python'],
    content: 'meta.embedded.line.bsx',
    terminator: `(?=['"]\\s*(?:[,)\\]}:]|$))|$`,
  },
];

const guarded = (rule, terminator) => {
  const copy = {...rule};
  if (copy.end !== undefined) copy.end = `(?:${copy.end})|${terminator}`;
  return copy;
};

for (const variant of variants) {
  const repository = Object.fromEntries(Object.entries(bsx.repository).map(([key, rule]) => [key, guarded(rule, variant.terminator)]));
  const exclude = `- string.interpolated.python - ${variant.content}`;
  const grammar = {
    $comment: `Generated by syntaxes/generate.mjs from bsx.tmLanguage.json; do not edit.`,
    scopeName: variant.scopeName,
    injectionSelector: variant.strings.map(scope => `L:${scope} ${exclude}`).join(', '),
    patterns: [
      {
        begin: `(?=<(?:${roots})\\b)`,
        end: variant.terminator,
        contentName: variant.content,
        patterns: [{include: '#markup'}],
      },
    ],
    repository,
  };
  writeFileSync(join(here, variant.file), `${JSON.stringify(grammar, null, 2)}\n`);
}
